CREATE TABLE IF NOT EXISTS transaccion (
    id      BIGINT PRIMARY KEY,
    fecha   DATE NOT NULL,
    monto   DECIMAL(15,2) NOT NULL,
    tipo    VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS transaccion_anomalia (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen          BIGINT,
    fecha_origen       DATE,
    monto_origen       DECIMAL(15,2),
    tipo_origen        VARCHAR(50),
    motivo             VARCHAR(300),
    fecha_deteccion    DATE
);

CREATE TABLE IF NOT EXISTS transaccion_error_lectura (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen          VARCHAR(50),
    fecha_origen       VARCHAR(50),
    monto_origen       VARCHAR(50),
    tipo_origen        VARCHAR(50),
    motivo             VARCHAR(300),
    fecha_deteccion    DATE
);

CREATE TABLE IF NOT EXISTS resumen_transaccion_diaria (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_proceso                   DATE,
    total_transacciones_validas     BIGINT,
    monto_total                     DECIMAL(18,2),
    total_anomalias                 BIGINT,
    total_omitidos                  BIGINT
);

CREATE TABLE IF NOT EXISTS cuenta_interes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id        BIGINT NOT NULL,
    nombre           VARCHAR(150),
    saldo_inicial    DECIMAL(15,2) NOT NULL,
    edad             INTEGER NOT NULL,
    tipo             VARCHAR(20) NOT NULL,
    tasa_aplicada    DECIMAL(6,4) NOT NULL,
    interes_mensual  DECIMAL(15,2) NOT NULL,
    saldo_final      DECIMAL(15,2) NOT NULL,
    fecha_calculo    DATE NOT NULL,
    CONSTRAINT uq_cuenta_interes_negocio UNIQUE (cuenta_id, nombre, saldo_inicial, edad, tipo)
);

CREATE TABLE IF NOT EXISTS interes_anomalia (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id_origen     VARCHAR(50),
    nombre_origen        VARCHAR(150),
    saldo_origen         VARCHAR(50),
    edad_origen          VARCHAR(20),
    tipo_origen          VARCHAR(50),
    motivo               VARCHAR(300),
    fecha_deteccion      DATE
);

CREATE TABLE IF NOT EXISTS cuenta_anual_detalle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id      BIGINT NOT NULL,
    fecha          DATE NOT NULL,
    transaccion    VARCHAR(30) NOT NULL,
    monto          DECIMAL(15,2) NOT NULL,
    descripcion    VARCHAR(300),
    CONSTRAINT uq_cuenta_anual_detalle_negocio UNIQUE (cuenta_id, fecha, transaccion, monto)
);

CREATE TABLE IF NOT EXISTS cuenta_anual_anomalia (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id             BIGINT,
    fecha                 DATE,
    transaccion           VARCHAR(30),
    monto                 DECIMAL(15,2),
    descripcion           VARCHAR(300),
    motivo                VARCHAR(300),
    fecha_deteccion       DATE,
    CONSTRAINT uq_cuenta_anual_anomalia_negocio UNIQUE (cuenta_id, fecha, transaccion, monto)
);

CREATE TABLE IF NOT EXISTS cuenta_anual_error_lectura (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id_origen       VARCHAR(50),
    fecha_origen           VARCHAR(50),
    transaccion_origen     VARCHAR(50),
    monto_origen           VARCHAR(50),
    descripcion_origen     VARCHAR(300),
    motivo                 VARCHAR(300),
    fecha_deteccion        DATE
);

CREATE TABLE IF NOT EXISTS cuenta_anual_resumen (
    cuenta_id            BIGINT PRIMARY KEY,
    total_movimientos    BIGINT,
    total_abonos         DECIMAL(18,2),
    total_cargos         DECIMAL(18,2),
    saldo_neto_anual     DECIMAL(18,2)
);

CREATE TABLE IF NOT EXISTS cuadratura_proceso (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job                  VARCHAR(80),
    archivo              VARCHAR(120),
    fecha_proceso        TIMESTAMP,
    registros_archivo    BIGINT,
    validos              BIGINT,
    anomalias            BIGINT,
    omitidos             BIGINT,
    cuadra               BOOLEAN
);
